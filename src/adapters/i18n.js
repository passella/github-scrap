export function detectLanguage(nav) {
  const navigatorObj = arguments.length > 0 ? nav : (typeof navigator !== 'undefined' ? navigator : null);
  if (!navigatorObj) return 'en';

  const candidates = [];
  if (Array.isArray(navigatorObj.languages)) {
    for (let i = 0; i < navigatorObj.languages.length; i += 1) {
      if (typeof navigatorObj.languages[i] === 'string') {
        candidates.push(navigatorObj.languages[i].toLowerCase());
      }
    }
  }

  if (typeof navigatorObj.language === 'string') {
    candidates.push(navigatorObj.language.toLowerCase());
  }

  for (let i = 0; i < candidates.length; i += 1) {
    const lang = candidates[i];
    if (lang.startsWith('pt')) {
      return 'pt-BR';
    }
    if (lang.startsWith('es')) {
      return 'es';
    }
    if (lang.startsWith('en')) {
      return 'en';
    }
  }

  return 'en';
}

export function t(lang, key, ...args) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  const value = dict[key];
  if (typeof value === 'function') {
    return value(...args);
  }
  return value || key;
}